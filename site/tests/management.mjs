assert.equal(stateSchema.safeParse({...initialState(),employees:[],entries:[e]}).success,false);
assert.equal(stateSchema.safeParse({...initialState(),employees:[p,{...p,id:crypto.randomUUID()}],entries:[]}).success,false);
