assert.throws(()=>entryFor(incomplete,'2026-09'),/Complete a ficha/);
p.contracts[0]={...p.contracts[0],effective:'2024-01',salary:2200,danger:true};
const e=entryFor(p,'2026-07');e.monthly.hours50=10;e.monthly.hours100=5;e.bonus=100;
assert.equal(e.monthly.hourlyBase,2904);assert.equal(calculate(e).extra50,198);assert.equal(calculate(e).extra100,132);
assert.equal(calculate(e).dsr,48.89);assert.equal(calculate(e).gross,3382.89);
assert.equal(calculate(e).annuity,44);
assert.equal(calculate(e).night,0);
const nightEmployee={...p,contracts:[{...p.contracts[0],nightEligible:true}]};
const nightEntry=entryFor(nightEmployee,'2026-07');nightEntry.monthly.nightHours=7;
assert.equal(calculate(nightEntry).nightReducedHours,8);
assert.equal(calculate(nightEntry).night,21.12);
assert.equal(calculate(nightEntry).danger,660);
const legacy=structuredClone(nightEntry);delete legacy.monthly.nightClockHours;delete legacy.monthly.nightEligible;
assert.equal(calculate(legacy).night,18.48);
const invalid=structuredClone(e);invalid.monthly.nightHours=7;
assert.equal(calculate(invalid).night,0);
assert.equal(stateSchema.safeParse({...initialState(),employees:[p],entries:[invalid]}).success,false);
const anniversary={...p,admission:'2024-08-15'};
assert.equal(calculate(entryFor(anniversary,'2026-07')).annuity,22);
assert.equal(calculate(entryFor(anniversary,'2026-08')).annuity,44);
p.contracts.push({...p.contracts[0],effective:'2026-08',salary:3000});
assert.equal(contractAt(p,'2026-07').salary,2200);assert.equal(contractAt(p,'2026-08').salary,3000);
assert.equal(e.salary,2200);assert.equal(entryFor(p,'2026-09').salary,3000);
assert.deepEqual(calendar('2026-07','2026-07-05,2026-07-05'),calendar('2026-07'));
