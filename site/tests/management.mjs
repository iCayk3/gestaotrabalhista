import assert from 'node:assert/strict';
import {blankEmployee,entryFor,calendar,contractAt} from '../lib/payroll/management.ts';
import {calculate,initialState} from '../lib/payroll/engine.ts';
import {stateSchema} from '../lib/payroll/validation.ts';
const p=blankEmployee();Object.assign(p,{name:'Pessoa teste',registration:'001',job:'Técnico',admission:'2024-01-01'});
const incomplete=blankEmployee();incomplete.name='Cadastro parcial';
